// Live-vs-repo drift check (npm run db:drift-sql > drift.sql).
// Builds the in-memory database from supabase/migrations (same as the finance gate), then prints ONE read-only SQL query.
// Run that query on the live project (Supabase SQL editor or the MCP execute_sql tool). It returns ONLY the differences:
//   function  <signature>  ONLY_LIVE | ONLY_IN_REPO | DIFFERENT_BODY   (bodies compared without comments and whitespace)
//   columns / triggers / indexes  <table>  ONLY_LIVE | ONLY_IN_REPO | DIFFERENT
// Zero rows = the cloud matches the repo exactly. The query writes nothing.
import { buildDb } from '../supabase/tests/golden/db.mjs';

const { db } = await buildDb({ log: false });
const EXT = `^(gin_|gtrgm|gist_|similarity|word_similarity|strict_word|show_trgm|set_limit|show_limit|unaccent)`;
const FN = `select p.proname||'('||pg_get_function_identity_arguments(p.oid)||')' t,
  md5(regexp_replace(regexp_replace(p.prosrc, '--[^\\n]*', '', 'g'), '[[:space:]]+', '', 'g')) m
  from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prokind = 'f' and p.proname !~ '${EXT}'`;
const COLS = `select table_name t, md5(string_agg(column_name||':'||data_type, ',' order by column_name)) m
  from information_schema.columns where table_schema = 'public' group by 1`;
const TRG = `select c.relname t, md5(string_agg(t.tgname||':'||p.proname, ',' order by t.tgname)) m
  from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  join pg_proc p on p.oid = t.tgfoid where n.nspname = 'public' and not t.tgisinternal group by 1`;
const IDX = `select tablename t, md5(string_agg(indexname, ',' order by indexname)) m
  from pg_indexes where schemaname = 'public' group by 1`;

const values = async (sql) => {
  const rows = (await db.query(sql)).rows;
  return rows.map((r) => `('${String(r.t).replace(/'/g, "''")}','${r.m}')`).join(',\n');
};
const part = (kind, l, r) => `select '${kind}' kind, coalesce(${l}.t, ${r}.t) name,
  case when ${l}.t is null then 'ONLY_IN_REPO' when ${r}.t is null then 'ONLY_LIVE' else 'DIFFERENT' end side
  from ${l} full join ${r} on ${r}.t = ${l}.t where ${l}.t is null or ${r}.t is null or ${l}.m <> ${r}.m`;

console.log(`-- Generated by scripts/db-drift-sql.mjs. Read-only. Zero rows = live matches the repo.
with rf(t,m) as (values ${await values(FN)}),
rc(t,m) as (values ${await values(COLS)}),
rt(t,m) as (values ${await values(TRG)}),
ri(t,m) as (values ${await values(IDX)}),
lf as (${FN}), lc as (${COLS}), lt as (${TRG}), li as (${IDX})
${part('function', 'lf', 'rf')}
union all ${part('columns', 'lc', 'rc')}
union all ${part('triggers', 'lt', 'rt')}
union all ${part('indexes', 'li', 'ri')}
order by 1, 3, 2;`);
process.exit(0);
